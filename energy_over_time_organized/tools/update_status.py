#!/usr/bin/env python3
"""Rebuild the experiment status table in energy_over_time_organized/README.md.

Reads every <NN_name>/experiment.json and rewrites the block between the
STATUS-TABLE markers. Pure standard library, so it runs on the login node.

    python3 tools/update_status.py          # rewrite README.md
    python3 tools/update_status.py --check  # exit 1 if README.md is stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
BEGIN = "<!-- STATUS-TABLE:BEGIN (generated by tools/update_status.py; do not edit by hand) -->"
END = "<!-- STATUS-TABLE:END -->"
STATUSES = ["planned", "running", "analysis", "complete", "superseded", "archived"]
REQUIRED = ["id", "title", "status", "owner", "updated", "question", "headline"]


def load_experiments():
    exps, errors = [], []
    for path in sorted(ROOT.glob("[0-9][0-9]_*/experiment.json")):
        try:
            meta = json.loads(path.read_text())
        except json.JSONDecodeError as exc:
            errors.append(f"{path.relative_to(ROOT)}: invalid JSON ({exc})")
            continue
        missing = [k for k in REQUIRED if not meta.get(k)]
        if missing:
            errors.append(f"{path.relative_to(ROOT)}: missing {', '.join(missing)}")
        if meta.get("status") not in STATUSES:
            errors.append(f"{path.relative_to(ROOT)}: status must be one of {STATUSES}")
        meta["_dir"] = path.parent.name
        exps.append(meta)
    return exps, errors


def render(exps):
    rows = [
        "| ID | Experiment | Status | Owner | Updated | Headline |",
        "|---|---|---|---|---|---|",
    ]
    for e in exps:
        d = e["_dir"]
        headline = e.get("headline", "").replace("|", "\\|").replace("\n", " ")
        rows.append(
            f"| {e.get('id', '')} | [{e.get('title', d)}]({d}/README.md) · [results]({d}/RESULTS.md) "
            f"| **{e.get('status', '?')}** | {e.get('owner', '')} | {e.get('updated', '')} | {headline} |"
        )
    return "\n".join(rows)


def main():
    exps, errors = load_experiments()
    for err in errors:
        print("ERROR:", err, file=sys.stderr)
    text = README.read_text()
    if BEGIN not in text or END not in text:
        sys.exit("README.md is missing the STATUS-TABLE markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{BEGIN}\n{render(exps)}\n{END}{tail}"
    if "--check" in sys.argv:
        stale = new != text
        if stale:
            print("README.md status table is stale: run python3 tools/update_status.py", file=sys.stderr)
        sys.exit(1 if (stale or errors) else 0)
    README.write_text(new)
    print(f"Updated status table: {len(exps)} experiments")
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
